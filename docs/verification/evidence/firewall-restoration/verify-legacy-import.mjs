import { chromium } from 'playwright';
import { startNewGame, waitForGameReady, exportThroughUi } from '../../../../scripts/browser/support.ts';
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const startedAt=new Date().toISOString();
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../../../../', import.meta.url)).replace(/\/$/, '');
const file=root+'/docs/verification/evidence/m5-chrome-final-production-complete-save.json';
const output=root+'/test-results/firewall-restoration';
const original=JSON.parse(readFileSync(file,'utf8'));
const browser=await chromium.launch({channel:'chrome'});
const page=await browser.newPage({viewport:{width:1512,height:771}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
await page.goto('http://localhost:5174');
assert.equal(await page.evaluate(()=>Reflect.has(window,'__CAMELLIA_INSPECT__')),false);
await startNewGame(page);
await page.getByRole('button',{name:'打开暂停菜单',exact:true}).click();
await page.getByRole('button',{name:'进度与存档',exact:true}).click();
const chooser=page.waitForEvent('filechooser');
await page.getByRole('button',{name:'导入存档',exact:true}).click();
await (await chooser).setFiles(file);
await page.getByRole('heading',{name:'确认导入进度',exact:true}).waitFor();
const preview=await page.locator('.dialog-description').innerText();
await page.screenshot({path:output+'/legacy-import-preview.png'});
await page.getByRole('button',{name:'确认替换',exact:true}).click();
await waitForGameReady(page);
await page.screenshot({path:output+'/legacy-import-warehouse.png'});
const imported=await exportThroughUi(page);
assert.equal(imported.payload.contentVersion,5);
assert.equal(imported.payload.ruleVersion,2);
for(const key of ['claimedRewardIds','completedObjectiveIds','completedRoomLayouts','playerPosition','bestResults','capabilities','activatedTeleportIds','campaignCompletedAt']) assert.deepEqual(imported.payload[key],original.payload[key],key);
assert.equal(imported.payload.claimedRewardIds.length,26);
writeFileSync(output+'/legacy-import-export.json',JSON.stringify(imported,null,2)+'\n');
await page.reload();
await page.getByRole('button',{name:'继续游戏',exact:true}).click();
await waitForGameReady(page);
const restored=await exportThroughUi(page);
assert.deepEqual(restored.payload,imported.payload);
assert.deepEqual(errors,[]);
writeFileSync(output+'/legacy-import-result.json',JSON.stringify({startedAt,finishedAt:new Date().toISOString(),browser:browser.version(),sourceSha256:createHash('sha256').update(readFileSync(file)).digest('hex'),packageManifestSha256:createHash('sha256').update(readFileSync(root+'/docs/verification/evidence/firewall-restoration/package.json')).digest('hex'),source:'docs/verification/evidence/m5-chrome-final-production-complete-save.json',method:'Normal UI file chooser, confirm replace, export, reload, continue, export. No game-state injection.',preview,from:{contentVersion:original.payload.contentVersion,ruleVersion:original.payload.ruleVersion,generation:original.saveGeneration},to:{contentVersion:imported.payload.contentVersion,ruleVersion:imported.payload.ruleVersion,generation:imported.saveGeneration,rewards:imported.payload.claimedRewardIds.length},restoredIdentically:true,errors},null,2)+'\n');
console.log('Real legacy full-collection save imported, exported, reloaded and restored: 26 rewards, content5/rule2.');
} catch(e) { await page.screenshot({path:output+'/legacy-import-failure.png'});console.log(await page.locator('#game-dialog').innerText());throw e; }
finally { await browser.close(); }
